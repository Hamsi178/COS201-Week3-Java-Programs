public class LinePrinter {
    public static void main(String[] args) {
        // print() keeps the cursor on the same line
        System.out.print("COS");
        System.out.print(" ");
        System.out.print("201");

        // println() finishes the line
        System.out.println();
        System.out.println("Java");
        // Output:
        // COS 201
        // Java
    }
}
